// Build client.js: wrap client/src/main.js in the dsh __ModuleLoader__
// factory and inline the frame probe and reader stylesheet.
//
//   node scripts/build-client.mjs          write client.js
//   node scripts/build-client.mjs --check  fail if client.js is stale

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

const source = await readFile(join(root, 'client/src/main.js'), 'utf8')
// tdoc composed its frame script by concatenation; the probe calls
// layoutTables() from table-layout.js, so that file goes first.
const probe = (await readFile(join(root, 'client/table-layout.js'), 'utf8')) + '\n' + (await readFile(join(root, 'client/frame-probe.js'), 'utf8'))
const reader = await readFile(join(root, 'client/reader.css'), 'utf8')

for (const marker of ['__FRAME_PROBE__', '__READER_CSS__']) {
  if (source.split(marker).length !== 2) throw new Error(`client/src/main.js must contain ${marker} exactly once`)
}

const body = source
  .replace('__FRAME_PROBE__', () => JSON.stringify(probe))
  .replace('__READER_CSS__', () => JSON.stringify(reader))

const indented = body.split('\n').map(line => (line ? '    ' + line : line)).join('\n')
const output = `// GENERATED by scripts/build-client.mjs from client/src/main.js — do not edit.
// SPDX-License-Identifier: AGPL-3.0-or-later
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    const module = { exports: {} }
${indented}
    return module.exports
  },
})
`

const target = join(root, 'client.js')
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== output) {
    console.error('client.js is stale: run node scripts/build-client.mjs')
    process.exit(1)
  }
} else {
  await writeFile(target, output)
  console.log(`wrote client.js (${output.length} bytes)`)
}
